// ---------------------------------------------------------------------------
// supabase/seeds/32_article_drafts.sql from content/article-drafts/*.mdx —
// the same drafts the composer's "Import drafts" loads on production
// (lib/content/article-drafts.ts parses them for the app; this module parses
// them the same way for the seed, and tests/unit/content/article-drafts.test.ts
// holds the two — and the committed seed — together).
//
// Regenerate after editing a draft: node scripts/build-article-drafts-seed.mjs
// ---------------------------------------------------------------------------

import matter from "gray-matter";

/** Deterministic ids, one per draft in file-name order (…0101, …0102, …). */
export function draftId(index) {
  return `a1530000-0000-4000-a000-${String(101 + index).padStart(12, "0")}`;
}

/** One draft file → the columns the seed writes (the app's parseArticleDraft). */
export function parseDraftForSeed(filename, raw) {
  const slug = filename.replace(/\.mdx$/, "");
  const { data, content } = matter(raw);
  if (!data.title || !data.description) return null;
  const cover = data.cover && typeof data.cover === "object" ? data.cover : null;
  const faq = Array.isArray(data.faq)
    ? data.faq
        .filter((item) => item && typeof item === "object")
        .map((item) => ({ q: String(item.q ?? "").trim(), a: String(item.a ?? "").trim() }))
        .filter((item) => item.q && item.a)
    : [];
  const int = (v) => (Number.isInteger(v) && v > 0 ? v : null);
  return {
    slug,
    title: String(data.title),
    seo_title: data.seoTitle ? String(data.seoTitle) : null,
    description: String(data.description),
    excerpt: data.excerpt ? String(data.excerpt) : null,
    body: content.replace(/^\n+/, ""),
    tags: Array.isArray(data.tags) ? data.tags.map(String) : [],
    category: typeof data.category === "string" ? data.category : null,
    faq,
    cover_url: cover && typeof cover.src === "string" ? cover.src : null,
    cover_alt: cover && typeof cover.alt === "string" ? cover.alt : null,
    cover_width: cover ? int(cover.width) : null,
    cover_height: cover ? int(cover.height) : null,
  };
}

const TAG = "$draft$";

function literal(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return String(value);
  const text = String(value);
  if (text.includes(TAG)) throw new Error(`A draft contains ${TAG}; pick another dollar-quote tag.`);
  return `${TAG}${text}${TAG}`;
}

function textArray(values) {
  return values.length === 0 ? "'{}'::text[]" : `array[${values.map(literal).join(", ")}]::text[]`;
}

export function buildArticleDraftsSeed(drafts) {
  const rows = drafts.map((d, i) =>
    [
      `  (`,
      `    '${draftId(i)}'::uuid,`,
      `    ${literal(d.slug)},`,
      `    ${literal(d.title)},`,
      `    ${literal(d.seo_title)},`,
      `    ${literal(d.description)},`,
      `    ${literal(d.excerpt)},`,
      `    ${literal(d.body)},`,
      `    ${textArray(d.tags)},`,
      `    ${literal(d.category)},`,
      `    ${literal(JSON.stringify(d.faq))}::jsonb,`,
      `    ${literal(d.cover_url)},`,
      `    ${literal(d.cover_alt)},`,
      `    ${literal(d.cover_width)}::integer,`,
      `    ${literal(d.cover_height)}::integer`,
      `  )`,
    ].join("\n"),
  );
  return `-- ---------------------------------------------------------------------------
-- 32_article_drafts.sql — GENERATED by scripts/build-article-drafts-seed.mjs
-- from content/article-drafts/*.mdx; never edit by hand (a unit test holds
-- it to the files).
--
-- The draft articles shipped for the owner's review, as DRAFT composer
-- articles (migration 0153), so a preview branch, the dev database and the
-- local stack show them at /admin/articles (sign in as dev_admin). Production
-- never runs seeds: there the owner presses "Import drafts" on
-- /admin/articles, which loads the same files.
--
-- No byline (the owner picks one), nothing scheduled or published.
-- Idempotent: fixed ids + ON CONFLICT DO NOTHING (a reseed keeps an edit).
-- No credential in here (the repo is public). Ids a1530000-…-000000000101 on.
-- ---------------------------------------------------------------------------

do $guard$
begin
  if (select count(*) from auth.users where email not like '%@dev.pipglyph.test'
                                        and email not like '%@pipglyph.test') > 25 then
    raise exception 'Refusing to seed dev data: this database has real users. Wrong target?';
  end if;
end
$guard$;

insert into public.articles (
  id, slug, title, seo_title, description, excerpt, body, tags, category, faq,
  cover_url, cover_alt, cover_width, cover_height, is_published
)
select
  v.id, v.slug, v.title, v.seo_title, v.description, v.excerpt, v.body, v.tags, v.category, v.faq,
  v.cover_url, v.cover_alt, v.cover_width, v.cover_height, false
from (values
${rows.join(",\n")}
) as v (
  id, slug, title, seo_title, description, excerpt, body, tags, category, faq,
  cover_url, cover_alt, cover_width, cover_height
)
on conflict do nothing;
`;
}
