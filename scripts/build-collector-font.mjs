// ---------------------------------------------------------------------------
// Regenerate the collector line's face (TODO 4.9b): public/fonts/
// Montserrat-Medium.ttf + .woff2, beside public/fonts/Montserrat-OFL.txt.
//
// The source is Google Fonts' Montserrat variable master (SIL OFL 1.1,
// github.com/google/fonts/tree/main/ofl/montserrat — `Montserrat[wght].ttf`
// and its OFL.txt), which is NOT in the repo: pass its folder. The script
//   1. instances the Medium weight (wght 500) with fontTools' instancer;
//   2. subsets it to COLLECTOR_TEXT — A–Z, a–z, 0–9, the slash, the hyphen,
//      the bullet, the dagger and the space: 67 code points, every one of
//      them in MPlantin's cmap. Satori falls back through EVERY registered
//      font (lib/render/card-fonts.ts registers this one LAST), so a glyph
//      only this face had would change existing cards' text on their next
//      re-bake; tests/unit/render/collector-font.test.ts holds the subset to
//      MPlantin's cmap and the registration order;
//   3. drops GSUB / GPOS (no kerning: both renderers lay the runs out from
//      the advances alone — lib/cards/collector-metrics.ts, generated by
//      scripts/generate-collector-metrics.mjs from the TTF this writes);
//   4. writes the WOFF2 the browser preview loads (app/globals.css
//      "CollectorLine", with ascent / descent / line-gap overrides from the
//      face's hhea so Windows draws the same line box as Satori).
//
//   node scripts/build-collector-font.mjs --source <folder with Montserrat[wght].ttf and OFL.txt>
//
// Needs Python 3 with fontTools + brotli (`python3 -m pip install fonttools
// brotli`). Commit the three outputs with the regenerated metrics table.
// ---------------------------------------------------------------------------

import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, statSync } from "node:fs";
import path from "node:path";
import { COLLECTOR_TEXT } from "./lib/collector-metrics.mjs";

const args = process.argv.slice(2);
const at = args.indexOf("--source");
const source = at >= 0 ? args[at + 1] : null;
if (!source) {
  console.error("usage: node scripts/build-collector-font.mjs --source <folder with Montserrat[wght].ttf and OFL.txt>");
  process.exit(1);
}
const variable = path.join(source, "Montserrat[wght].ttf");
const licence = path.join(source, "OFL.txt");
for (const file of [variable, licence]) {
  if (!existsSync(file)) {
    console.error(`✗ missing ${file}`);
    process.exit(1);
  }
}

const outDir = path.resolve("public/fonts");
const ttf = path.join(outDir, "Montserrat-Medium.ttf");
const woff2 = path.join(outDir, "Montserrat-Medium.woff2");

const python = `
import sys
from fontTools.ttLib import TTFont, woff2
from fontTools.varLib import instancer
from fontTools import subset
src, out_ttf, out_woff2, text = sys.argv[1:5]
font = instancer.instantiateVariableFont(TTFont(src), {"wght": 500}, inplace=False, updateFontNames=True)
opts = subset.Options()
opts.layout_features = []            # no GSUB / GPOS: advances only, in both renderers
opts.name_IDs = ["*"]; opts.name_legacy = True; opts.name_languages = ["*"]
opts.notdef_outline = True; opts.glyph_names = True; opts.hinting = True
opts.drop_tables += ["DSIG", "GSUB", "GPOS", "GDEF", "STAT"]
sub = subset.Subsetter(options=opts)
sub.populate(text=text)
sub.subset(font)
font.save(out_ttf)
woff2.compress(out_ttf, out_woff2)
`;
execFileSync("python3", ["-c", python, variable, ttf, woff2, COLLECTOR_TEXT], { stdio: "inherit" });
copyFileSync(licence, path.join(outDir, "Montserrat-OFL.txt"));
for (const file of [ttf, woff2]) console.log(`✓ ${path.relative(process.cwd(), file)}: ${statSync(file).size} bytes`);
console.log("✓ Montserrat-OFL.txt copied");
